//! Renders `bindings/AbiConstants.ts`: the numbers and names the TypeScript host must agree on,
//! from the Rust tables, so the host never restates one. Written by the `ts` feature's test.

use crate::abi::{self, AbiError, InitResult};
use crate::calls::KvBackend;
use crate::ops::{ts_reply_names, OPS};
use crate::{encode, Capability, Group};
use std::collections::BTreeSet;
use std::fmt::Write;
use std::string::String;

fn q(s: &str) -> String {
    format!("{s:?}")
}

/// The TypeScript identifiers a generated type name references (`Array<NodeInfo>` -> NodeInfo).
fn referenced(ts: &str, out: &mut BTreeSet<String>) {
    for word in ts.split(|c: char| !c.is_ascii_alphanumeric() && c != '_') {
        let builtin = matches!(word, "" | "null" | "Array" | "number" | "bigint" | "string");
        if !builtin && word.chars().next().is_some_and(|c| c.is_ascii_uppercase()) {
            out.insert(word.into());
        }
    }
}

/// The serde tag of a KV backend: its text, or the one key of its map.
fn kv_tag(b: &KvBackend) -> String {
    let value: ciborium::Value = crate::decode(&encode(b)).expect("a KvBackend re-decodes");
    match value {
        ciborium::Value::Text(t) => t,
        ciborium::Value::Map(m) => m[0].0.as_text().expect("a text tag").into(),
        other => panic!("unexpected KvBackend encoding {other:?}"),
    }
}

pub fn render() -> String {
    let replies = ts_reply_names();
    let mut types = BTreeSet::from(["Capability".to_string(), "Group".to_string()]);
    for (name, reply) in &replies {
        types.insert((*name).into());
        referenced(reply, &mut types);
    }
    let mut o = String::from(
        "// Generated by citadel-app-sdk-types (`cargo test --features ts`). Do not edit.\n",
    );
    for t in &types {
        writeln!(o, "import type {{ {t} }} from \"./{t}\";").unwrap();
    }
    writeln!(o).unwrap();
    for (name, value) in [
        ("ABI_NAMESPACE", abi::NAMESPACE),
        ("ABI_ID", abi::ABI_ID),
        ("MEMORY_IMPORT", abi::MEMORY),
        ("REPLY_LEN", abi::REPLY_LEN),
        ("REPLY_READ", abi::REPLY_READ),
        ("EXPORT_ALLOC", abi::EXPORT_ALLOC),
        ("EXPORT_FREE", abi::EXPORT_FREE),
        ("EXPORT_INIT", abi::EXPORT_INIT),
        ("EXPORT_EVENT", abi::EXPORT_EVENT),
        ("EXPORT_FRAME", abi::EXPORT_FRAME),
        ("REFUSED_UNKNOWN_OP", abi::REFUSED_UNKNOWN_OP),
        ("REFUSED_BAD_ARGUMENTS", abi::REFUSED_BAD_ARGUMENTS),
        ("REFUSED_REQUEST_BYTES", abi::REFUSED_REQUEST_BYTES),
    ] {
        writeln!(o, "export const {name} = {} as const;", q(value)).unwrap();
    }
    let list = |xs: &[&str]| xs.iter().map(|x| q(x)).collect::<Vec<_>>().join(", ");
    writeln!(
        o,
        "export const REQUIRED_EXPORTS = [{}] as const;",
        list(&abi::REQUIRED_EXPORTS)
    )
    .unwrap();
    writeln!(
        o,
        "export const OPTIONAL_EXPORTS = [{}] as const;",
        list(&abi::OPTIONAL_EXPORTS)
    )
    .unwrap();
    writeln!(o, "export const PAGE_BYTES = {} as const;", abi::PAGE_BYTES).unwrap();
    writeln!(
        o,
        "export const IHTTP_MAX_CHUNK_BYTES = {} as const;",
        abi::IHTTP_MAX_CHUNK_BYTES
    )
    .unwrap();
    writeln!(
        o,
        "export const IHTTP_INITIAL_CREDIT = {} as const;",
        abi::IHTTP_INITIAL_CREDIT
    )
    .unwrap();
    let intrinsic: Vec<&str> = Capability::INTRINSIC.iter().map(|c| c.name()).collect();
    writeln!(
        o,
        "/** Held by every install; declarable without listing. */"
    )
    .unwrap();
    writeln!(
        o,
        "export const INTRINSIC_CAPABILITIES = [{}] as const satisfies readonly Capability[];\n",
        list(&intrinsic)
    )
    .unwrap();

    writeln!(o, "export const ABI_ERROR = {{").unwrap();
    for e in AbiError::ALL {
        writeln!(o, "  {}: {},", e.name(), e.code()).unwrap();
    }
    writeln!(o, "}} as const;\n\nexport const INIT_RESULT = {{").unwrap();
    for r in InitResult::ALL {
        writeln!(o, "  {}: {},", r.name(), r.code()).unwrap();
    }
    writeln!(o, "}} as const;\n\n/** Import name -> group index. */\nexport const GROUPS: Readonly<Record<Group, number>> = {{").unwrap();
    for g in Group::ALL {
        writeln!(o, "  {}: {},", g.import_name(), g.index()).unwrap();
    }
    writeln!(o, "}};\n\n/** The group each capability opens. */\nexport const CAPABILITY_GROUP: Readonly<Record<Capability, Group>> = {{").unwrap();
    for c in Capability::ALL {
        writeln!(o, "  {}: {},", q(c.name()), q(c.group().import_name())).unwrap();
    }
    writeln!(o, "}};\n\n/** The capability a Kv* op needs, by its `backend` tag. */\nexport const KV_BACKEND_CAPABILITY = {{").unwrap();
    let node = KvBackend::Node {
        node_id: String::new(),
    };
    for b in [KvBackend::User, KvBackend::Scope, node, KvBackend::Local] {
        writeln!(o, "  {}: {},", kv_tag(&b), q(b.capability().name())).unwrap();
    }
    writeln!(o, "}} as const;\n\n/** Every op. `capability: null` = decided by the arguments (KV_BACKEND_CAPABILITY). */").unwrap();
    writeln!(o, "export const OPS = [").unwrap();
    for op in OPS {
        let cap = op.capability.map_or("null".into(), |c| q(c.name()));
        writeln!(
            o,
            "  {{ group: {}, op: {}, name: {}, capability: {cap} }},",
            q(op.group.import_name()),
            op.op,
            q(op.name)
        )
        .unwrap();
    }
    writeln!(o, "] as const satisfies readonly {{ group: Group; op: number; name: string; capability: Capability | null }}[];\n").unwrap();
    writeln!(
        o,
        "/** Op name -> its argument struct. */\nexport type OpArgs = {{"
    )
    .unwrap();
    for (name, _) in &replies {
        writeln!(o, "  {name}: {name};").unwrap();
    }
    writeln!(
        o,
        "}};\n\n/** Op name -> the `ok` payload of its HostReply. */\nexport type OpReplies = {{"
    )
    .unwrap();
    for (name, reply) in &replies {
        writeln!(o, "  {name}: {reply};").unwrap();
    }
    writeln!(o, "}};").unwrap();
    o
}
