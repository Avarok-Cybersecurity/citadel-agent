//! The signed-app fixture (`fixtures/signed-app.json`) that every other verifier of this
//! signature is held to: the browser wasm client's export and the page's verifier test read
//! it. ML-DSA signing is deterministic, so the whole file is regenerated here and compared byte
//! for byte; with `CITADEL_WRITE_APP_SIGNATURE_FIXTURE=1` it is rewritten instead.
//!
//! It carries a valid signature and what its controls need: a second publisher key, and a
//! signature by the right key over the right fields under another domain. Its seeds are fixed
//! test values; neither is, or derives, a real key.

use super::*;

const SEED: [u8; SEED_LEN] = [7; SEED_LEN];
const OTHER_SEED: [u8; SEED_LEN] = [9; SEED_LEN];
const ID: &str = "com.acme.kanban";
const VERSION: &str = "1.4.0";
const MANIFEST: &str = r#"{"format":1,"id":"com.acme.kanban","version":"1.4.0"}"#;
const WASM: &[u8] = b"\0asm\x01\0\0\0";
const WRONG_DOMAIN: &[u8] = b"citadel-app-v0\0";

fn fixture_path() -> std::path::PathBuf {
    std::path::Path::new(env!("CARGO_MANIFEST_DIR")).join("fixtures/signed-app.json")
}

/// A signature by `seed`'s key over this app's message, with `DOMAIN` swapped for `domain`.
fn signed_under(domain: &[u8], digests: &ArtifactDigests) -> String {
    let mut xi = Seed::default();
    xi.copy_from_slice(&SEED);
    let raw = SigningKey::<MlDsa65>::from_seed(&xi);
    let body = &signed_message(ID, VERSION, digests).unwrap()[DOMAIN.len()..];
    let signature: Signature<MlDsa65> = raw.sign(&[domain, body].concat());
    hex::encode(signature.encode().as_slice())
}

fn expected() -> String {
    let key = AppSigningKey::from_seed(&SEED);
    let digests = ArtifactDigests::of(MANIFEST.as_bytes(), WASM);
    let manifest_json = MANIFEST.replace('"', "\\\"");
    format!(
        "{{\n  \"about\": \"Generated by citadel-app-signature fixture_tests. Hex is lowercase; the signature is app.mldsa.sig's text.\",\n  \"domain\": \"citadel-app-v1\\\\0\",\n  \"app_id\": \"{ID}\",\n  \"version\": \"{VERSION}\",\n  \"manifest\": \"{manifest_json}\",\n  \"wasm_hex\": \"{}\",\n  \"manifest_sha256\": \"{}\",\n  \"wasm_sha256\": \"{}\",\n  \"public_key_hex\": \"{}\",\n  \"other_public_key_hex\": \"{}\",\n  \"signature_hex\": \"{}\",\n  \"wrong_domain_signature_hex\": \"{}\"\n}}\n",
        hex::encode(WASM),
        hex::encode(digests.manifest),
        hex::encode(digests.wasm),
        key.public_key_hex(),
        AppSigningKey::from_seed(&OTHER_SEED).public_key_hex(),
        key.sign(ID, VERSION, &digests).unwrap(),
        signed_under(WRONG_DOMAIN, &digests),
    )
}

#[test]
fn the_shared_signed_app_fixture_is_what_this_crate_signs() {
    let want = expected();
    if std::env::var_os("CITADEL_WRITE_APP_SIGNATURE_FIXTURE").is_some() {
        std::fs::write(fixture_path(), &want).expect("write the signed-app fixture");
    }
    let have = std::fs::read_to_string(fixture_path()).expect("read the signed-app fixture");
    assert!(
        have == want,
        "fixtures/signed-app.json is not what this crate signs"
    );
}

#[test]
fn the_fixture_verifies_and_each_of_its_controls_is_refused() {
    let key = AppSigningKey::from_seed(&SEED).public_key_hex();
    let other = AppSigningKey::from_seed(&OTHER_SEED).public_key_hex();
    let digests = ArtifactDigests::of(MANIFEST.as_bytes(), WASM);
    let signature = AppSigningKey::from_seed(&SEED)
        .sign(ID, VERSION, &digests)
        .unwrap();
    assert_eq!(verify(&key, ID, VERSION, &digests, &signature), Ok(()));
    let mut tampered_wasm = WASM.to_vec();
    tampered_wasm[7] ^= 1;
    let tampered = [
        ArtifactDigests::of(MANIFEST.as_bytes(), &tampered_wasm),
        ArtifactDigests::of(MANIFEST.replace("1.4.0", "1.4.1").as_bytes(), WASM),
    ];
    for digests in tampered {
        assert_eq!(
            verify(&key, ID, VERSION, &digests, &signature),
            Err(Refusal::Invalid)
        );
    }
    assert_eq!(
        verify(&other, ID, VERSION, &digests, &signature),
        Err(Refusal::Invalid)
    );
    assert!(matches!(
        verify(
            &key,
            ID,
            VERSION,
            &digests,
            &signature[..signature.len() - 2]
        ),
        Err(Refusal::MalformedSignature(_))
    ));
    let wrong_domain = signed_under(WRONG_DOMAIN, &digests);
    assert_eq!(
        verify(&key, ID, VERSION, &digests, &wrong_domain),
        Err(Refusal::Invalid)
    );
}
